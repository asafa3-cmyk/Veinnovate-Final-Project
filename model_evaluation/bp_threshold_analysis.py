# ---------------------------------------------------------------------------
# Part 2: Regression error-tolerance (coverage) curves
# ---------------------------------------------------------------------------

tolerances = np.linspace(0, 30, 301)  # 0..30 mmHg, 0.1 mmHg steps

def coverage_curve(y_true, y_pred, tolerances):
    abs_err = np.abs(y_true - y_pred)
    return np.array([100.0 * np.mean(abs_err <= t) for t in tolerances]), abs_err

sbp_cov, sbp_abs_err = coverage_curve(SBP_true, SBP_pred, tolerances)
dbp_cov, dbp_abs_err = coverage_curve(DBP_true, DBP_pred, tolerances)

def reg_stats(err_signed, abs_err):
    return {
        "MAE": float(np.mean(abs_err)),
        "median_AE": float(np.median(abs_err)),
        "RMSE": float(np.sqrt(np.mean(err_signed ** 2))),
        "bias_mean_signed_error": float(np.mean(err_signed)),
        "error_SD": float(np.std(err_signed)),
        "p90_abs_error": float(np.percentile(abs_err, 90)),
        "p95_abs_error": float(np.percentile(abs_err, 95)),
    }

sbp_signed_err = SBP_pred - SBP_true
dbp_signed_err = DBP_pred - DBP_true
sbp_stats = reg_stats(sbp_signed_err, sbp_abs_err)
dbp_stats = reg_stats(dbp_signed_err, dbp_abs_err)

mark_points = [5, 10, 15]
sbp_marks = {t: float(100.0 * np.mean(sbp_abs_err <= t)) for t in mark_points}
dbp_marks = {t: float(100.0 * np.mean(dbp_abs_err <= t)) for t in mark_points}

fig_cov, ax_cov = plt.subplots(1, 1, figsize=(7.5, 6.2), dpi=200)
ax_cov.plot(tolerances, sbp_cov, color=COLORS["SBP"], label="SBP", linewidth=2)
ax_cov.plot(tolerances, dbp_cov, color=COLORS["DBP"], label="DBP", linewidth=2)

for t in mark_points:
    ax_cov.axvline(t, color="gray", linestyle=":", linewidth=0.8)
    ax_cov.plot(t, sbp_marks[t], "o", color=COLORS["SBP"], markersize=5)
    ax_cov.plot(t, dbp_marks[t], "o", color=COLORS["DBP"], markersize=5)
    ax_cov.annotate(f"{sbp_marks[t]:.1f}%", (t, sbp_marks[t]), textcoords="offset points",
                     xytext=(6, 4), fontsize=8, color=COLORS["SBP"])
    ax_cov.annotate(f"{dbp_marks[t]:.1f}%", (t, dbp_marks[t]), textcoords="offset points",
                     xytext=(6, -12), fontsize=8, color=COLORS["DBP"])

ax_cov.set_xlabel("Absolute-Error Tolerance (mmHg)")
ax_cov.set_ylabel("Percentage of Predictions Within Tolerance (%)")
ax_cov.set_title("Prediction Coverage versus Absolute-Error Tolerance", fontsize=13, pad=28)
ax_cov.text(0.5, 1.03, SUBTITLE, transform=ax_cov.transAxes, ha="center", va="bottom", fontsize=9, color="#444444")
ax_cov.set_xlim(0, 30)
ax_cov.set_ylim(0, 101)
ax_cov.legend(loc="lower right", fontsize=9.5, frameon=True)
ax_cov.grid(alpha=0.25)
fig_cov.savefig(f"{OUT_DIR}/coverage_vs_error_tolerance.png", dpi=200, bbox_inches="tight")
fig_cov.savefig(f"{OUT_DIR}/coverage_vs_error_tolerance.svg", bbox_inches="tight")
plt.close(fig_cov)

