"""
Retrospective threshold-discrimination analysis for the selected V6PRO+SSL
PersonalDelta three-head ensemble (v6_track_b_ensemble_42_43_44).

Read-only post-hoc evaluation. Does NOT touch the source NPZ, does not
re-run inference, does not retrain/recalibrate anything. Writes only new
figures / metrics files into a separate output directory.

Data source (uploaded, local only): RAW_PREDICTIONS.npz
Arrays used: target, v6_track_b_ensemble_42_43_44, strictly_later, subjects
Eligible rows = strictly_later mask (6196 of 6410); calibration-anchor rows excluded.

IMPORTANT INTERPRETATION NOTE (see written report to user):
This is a regression model. It has no intrinsic ROC-AUC. Each ROC/PR-AUC
below is generated by converting the continuous ground truth into a binary
endpoint at a chosen clinical cut-point, then using the model's continuous
prediction as a discrimination score swept across its own decision
threshold. Changing the ground-truth cut-point (e.g. SBP>=130 vs >=140)
produces a different curve and a different AUC. This is a retrospective
threshold-discrimination analysis, not a clinical diagnosis or regulatory
performance claim.
"""
import json
import numpy as np
from sklearn.metrics import roc_curve, auc, precision_recall_curve, average_precision_score, confusion_matrix
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

RNG_SEED = 42
N_BOOTSTRAP = 2000

IN_PATH = "/sessions/upbeat-lucid-dirac/mnt/uploads/RAW_PREDICTIONS.npz"
OUT_DIR = "/sessions/upbeat-lucid-dirac/mnt/outputs/bp_threshold_eval"
import os
os.makedirs(OUT_DIR, exist_ok=True)

d = np.load(IN_PATH, allow_pickle=True)
target_all = d["target"]                      # (6410, 2) SBP, DBP
pred_all = d["v6_track_b_ensemble_42_43_44"]   # (6410, 2) SBP, DBP
mask = d["strictly_later"]                     # (6410,) bool
subjects_all = d["subjects"]                   # (6410,) subject ids

assert target_all.shape == (6410, 2)
assert pred_all.shape == (6410, 2)
assert mask.sum() == 6196
assert len(np.unique(subjects_all)) == 214

target = target_all[mask]
pred = pred_all[mask]
subjects = subjects_all[mask]

SBP_true, DBP_true = target[:, 0], target[:, 1]
SBP_pred, DBP_pred = pred[:, 0], pred[:, 1]

COLORS = {"SBP": "#1f77b4", "DBP": "#d62728"}

# ---------------------------------------------------------------------------
# Part 1: ROC / PR threshold-discrimination analysis
# ---------------------------------------------------------------------------

def patient_clustered_bootstrap_auc(y_true, y_score, subj_ids, n_boot=N_BOOTSTRAP, seed=RNG_SEED):
    """Resample patients (with replacement), not individual readings."""
    rng = np.random.default_rng(seed)
    unique_subj = np.unique(subj_ids)
    n_subj = len(unique_subj)
    # index lookup per subject
    subj_to_idx = {s: np.where(subj_ids == s)[0] for s in unique_subj}
    aucs = []
    for _ in range(n_boot):
        sampled_subj = rng.choice(unique_subj, size=n_subj, replace=True)
        idx = np.concatenate([subj_to_idx[s] for s in sampled_subj])
        yt, ys = y_true[idx], y_score[idx]
        if len(np.unique(yt)) < 2:
            continue
        fpr, tpr, _ = roc_curve(yt, ys)
        aucs.append(auc(fpr, tpr))
    aucs = np.array(aucs)
    lo, hi = np.percentile(aucs, [2.5, 97.5])
    return lo, hi, len(aucs)

endpoints = [
    ("SBP", ">=130", SBP_true, SBP_pred, 130.0),
    ("SBP", ">=140", SBP_true, SBP_pred, 140.0),
    ("DBP", ">=80",  DBP_true, DBP_pred, 80.0),
    ("DBP", ">=90",  DBP_true, DBP_pred, 90.0),
]

roc_results = {}
pr_results = {}
summary_rows = []

plt.rcParams.update({"font.size": 11})
SUBTITLE = "V6PRO+SSL PersonalDelta ensemble · retrospective · N=6196 readings / 214 subjects"

fig_roc, ax_roc = plt.subplots(1, 1, figsize=(7.5, 6.2), dpi=200)
fig_pr, ax_pr = plt.subplots(1, 1, figsize=(7.5, 6.2), dpi=200)

linestyles = {130.0: "-", 140.0: "--", 80.0: "-", 90.0: "--"}

for var, label, y_true_cont, y_score, cut in endpoints:
    y_bin = (y_true_cont >= cut).astype(int)
    n_pos, n_neg = int(y_bin.sum()), int((1 - y_bin).sum())
    pct_pos = 100.0 * n_pos / len(y_bin)

    reliable = (n_pos >= 10) and (n_neg >= 10)  # minimal-reliability flag

    fpr, tpr, roc_thr = roc_curve(y_bin, y_score)
    roc_auc = auc(fpr, tpr)

    prec, rec, pr_thr = precision_recall_curve(y_bin, y_score)
    pr_auc = average_precision_score(y_bin, y_score)

    ci_lo, ci_hi, n_valid_boot = patient_clustered_bootstrap_auc(y_bin, y_score, subjects)

    # Confusion matrix / sens / spec / PPV / NPV at prediction threshold == ground-truth cut
    pred_bin_at_cut = (y_score >= cut).astype(int)
    tn, fp, fn, tp = confusion_matrix(y_bin, pred_bin_at_cut, labels=[0, 1]).ravel()
    sens = tp / (tp + fn) if (tp + fn) > 0 else float("nan")
    spec = tn / (tn + fp) if (tn + fp) > 0 else float("nan")
    ppv = tp / (tp + fp) if (tp + fp) > 0 else float("nan")
    npv = tn / (tn + fn) if (tn + fn) > 0 else float("nan")

    key = f"{var}_{label}"
    roc_results[key] = dict(fpr=fpr.tolist(), tpr=tpr.tolist(), auc=float(roc_auc))
    pr_results[key] = dict(precision=prec.tolist(), recall=rec.tolist(), ap=float(pr_auc))

    summary_rows.append({
        "variable": var,
        "ground_truth_threshold_mmHg": cut,
        "endpoint_label": f"{var} {label} mmHg",
        "n_eligible_rows": int(len(y_bin)),
        "n_positive": n_pos,
        "n_negative": n_neg,
        "pct_positive": round(pct_pos, 2),
        "reliable_sample_flag": "OK" if reliable else "EXPLORATORY_LOW_N",
        "roc_auc": round(float(roc_auc), 4),
        "roc_auc_ci95_low": round(float(ci_lo), 4) if not np.isnan(ci_lo) else None,
        "roc_auc_ci95_high": round(float(ci_hi), 4) if not np.isnan(ci_hi) else None,
        "bootstrap_valid_resamples": n_valid_boot,
        "pr_auc": round(float(pr_auc), 4),
        "sensitivity_at_gt_cut": round(float(sens), 4),
        "specificity_at_gt_cut": round(float(spec), 4),
        "ppv_at_gt_cut": round(float(ppv), 4),
        "npv_at_gt_cut": round(float(npv), 4),
        "tp": int(tp), "fp": int(fp), "fn": int(fn), "tn": int(tn),
    })

    ci_str = f" (95% CI {ci_lo:.3f}–{ci_hi:.3f})" if not np.isnan(ci_lo) else ""
    flag_str = "" if reliable else " [exploratory: low N]"
    ax_roc.plot(fpr, tpr, color=COLORS[var], linestyle=linestyles[cut],
                label=f"{var} {label} mmHg (AUC={roc_auc:.3f}{flag_str})")
    ax_pr.plot(rec, prec, color=COLORS[var], linestyle=linestyles[cut],
               label=f"{var} {label} mmHg (AP={pr_auc:.3f}{flag_str})")

ax_roc.plot([0, 1], [0, 1], color="gray", linestyle=":", linewidth=1, label="Chance (AUC=0.500)")
ax_roc.set_xlabel("False Positive Rate")
ax_roc.set_ylabel("True Positive Rate")
ax_roc.set_title("ROC Curves for Blood-Pressure Threshold Discrimination", fontsize=13, pad=28)
ax_roc.text(0.5, 1.03, SUBTITLE, transform=ax_roc.transAxes, ha="center", va="bottom", fontsize=9, color="#444444")
ax_roc.legend(loc="upper left", bbox_to_anchor=(1.02, 1.0), fontsize=8.5, frameon=True, borderaxespad=0)
ax_roc.set_xlim(-0.02, 1.02)
ax_roc.set_ylim(-0.02, 1.02)
fig_roc.savefig(f"{OUT_DIR}/roc_curves_bp_thresholds.png", dpi=200, bbox_inches="tight")
fig_roc.savefig(f"{OUT_DIR}/roc_curves_bp_thresholds.svg", bbox_inches="tight")

ax_pr.set_xlabel("Recall")
ax_pr.set_ylabel("Precision")
ax_pr.set_title("Precision–Recall Curves for Blood-Pressure Threshold Discrimination", fontsize=13, pad=28)
ax_pr.text(0.5, 1.03, SUBTITLE, transform=ax_pr.transAxes, ha="center", va="bottom", fontsize=9, color="#444444")
ax_pr.legend(loc="upper left", bbox_to_anchor=(1.02, 1.0), fontsize=8.5, frameon=True, borderaxespad=0)
ax_pr.set_xlim(-0.02, 1.02)
ax_pr.set_ylim(-0.02, 1.02)
fig_pr.savefig(f"{OUT_DIR}/pr_curves_bp_thresholds.png", dpi=200, bbox_inches="tight")
fig_pr.savefig(f"{OUT_DIR}/pr_curves_bp_thresholds.svg", bbox_inches="tight")

plt.close(fig_roc)
